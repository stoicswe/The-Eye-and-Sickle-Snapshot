-- ===========================================================================
-- V2 — core game state.
--
-- Every table below is SERVER-OWNED game state (Invariant I14). None of it is
-- ever written to a player's AT Protocol PDS, and none of it is ever accepted
-- from a client without validation. AT Proto supplies a DID and nothing else.
--
-- This migration satisfies the five FIRM constraints in
-- docs/architecture/06-data-model.md §1. The table sketches in that doc's §2
-- are tagged [PROPOSAL]; where the sketch and the design docs disagree, the
-- design docs win and the deviation is called out in a comment beginning
-- "DEVIATION FROM 06 §2".
--
--   1. All game state lives here.                                     (I14)
--   2. The public ledger is FIRST-CLASS ROWS, not a derived view.
--      docs/design/01-core-resources.md §2.2 — investigators, player and NPC,
--      follow ethecoin flows to build evidence. Indexed for BOTH counterparties.
--   3. Provenance chains queryable by item_id with chain_depth range access.
--      docs/architecture/04-item-provenance.md §6.1.
--   4. The compute ledger is reconstructable and fully attributable, and a
--      DISCREPANCY between a rig's ceiling and the sum of its allocations is
--      REPRESENTABLE — that discrepancy is the manual-audit signal for a hidden
--      hostile miner (docs/design/04-mining.md §3.1). Nothing here prevents one.
--   5. faction_reputation and validator_reputation are DIFFERENT THINGS.
--      Faction reputation lives in this file, in `faction_reputations`, keyed by
--      player_id. Validator reputation lives in db/migration/federation, in
--      `validators`, keyed by a SERVER's DID. No shared column, no shared key,
--      and therefore no join path. See docs/design/glossary.md.
--
-- CONVENTIONS ESTABLISHED HERE (the other systems build on these):
--
--   * uuid primary keys, generated by the server, never by the client.
--   * TIMESTAMP WITH TIME ZONE everywhere. Never `timestamp`; a self-hoster in a different
--     zone must not get a different game.
--   * Enumerations are `text` + a named CHECK, not PostgreSQL ENUM types. Enum
--     values are cheap to add and effectively impossible to remove or rename,
--     and half these vocabularies are still [PROPOSAL]. The Java side maps them
--     with exhaustive switches (server `persistence/EnumColumns`), so a renamed
--     constant is a compile error and `SchemaVocabularyTest` proves the Java
--     spellings and these CHECK lists agree.
--   * Ethecoin columns are `numeric(78,0)` named `*_wei` — integral wei, 1e-18
--     EC, per protocol `Ethecoin`. ⚠ NOT bigint: at 18 decimals a bigint tops
--     out at 9.22 EC, less than one firmware image. Cycle columns are named
--     `*_cycles`. The suffixes are load-bearing: `persistence/EconomyColumns`
--     refuses to read an ethecoin amount out of a cycles column, which is
--     Invariant I1 made mechanical at the persistence boundary.
--   * `row_version` on every row that a concurrent request can mutate. Updates
--     are `... SET row_version = row_version + 1 WHERE id = ? AND row_version = ?`.
--   * JSON for genuinely document-shaped data only: signed payloads, item
--     attrs, installed modules. Everything relational stays relational
--     (docs/architecture/06 §4).
-- ===========================================================================


-- ---------------------------------------------------------------------------
-- Shared validation helper.
--
-- A DID is the portable player/server identity (docs/architecture/02 §1) and it
-- appears in a dozen columns across two migrations. Keeping the shape rule in
-- ONE immutable function means it cannot drift between tables; inlining the
-- regex twelve times means it eventually will. This is a shape check, not an
-- authentication check — proving a DID resolves to a key is the server's job at
-- sign-in, and no CHECK constraint can do it.
-- ---------------------------------------------------------------------------
CREATE ALIAS is_did FOR "io.github.stoicswe.eyeandsickle.server.identity.Did.isWellFormed";

-- ---------------------------------------------------------------------------
-- JSON shape checks, replacing Postgres's jsonb_typeof().
--
-- Two aliases, not one with a parameter: 'object' and 'array' are different
